// Helper to clean bullet text
function cleanBullet(text) {
  let cleaned = text
    .replace(/^[\s▪️\-*~•\d\.\)]+/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .trim();
  
  // Fix minor punctuation/typos while maintaining technical meaning
  cleaned = cleaned.replace(/\s+/g, ' ');
  return cleaned;
}

